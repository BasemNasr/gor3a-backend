def match_curated_key(name: str) -> Optional[str]:
    """Matches a drug commercial name to curated knowledge keys."""
    if not name:
        return None
    clean = re.sub(r"[^a-zA-Z0-9\s]", " ", name).lower().strip()
    words = clean.split()
    if not words:
        return None

    # Check 1: single first brand word (e.g. 'augmentin', 'flagyl', 'antinal', 'cataflam')
    first_word = words[0]
    if first_word in CURATED_CLINICAL_PROFILES:
        return first_word

    # Check 2: multi-word phrases (e.g. 'limitless fortalase', '1 2 3')
    if len(words) >= 2:
        phrase = f"{words[0]} {words[1]}"
        if phrase in CURATED_CLINICAL_PROFILES:
            return phrase

    # Check 3: substring search in keys
    for k in CURATED_CLINICAL_PROFILES:
        if k in clean:
            return k

    return None


def match_generic_key(generic_name: str) -> Optional[Dict[str, Any]]:
    """Matches active ingredients or scientific name to clinical profile."""
    if not generic_name:
        return None
    gen_clean = generic_name.lower()
    for gen_k, profile in GENERIC_INGREDIENT_MAP.items():
        if gen_k in gen_clean:
            return profile
    return None


def get_clinical_knowledge(
    drug_name: Optional[str] = None,
    generic_name: Optional[str] = None,
    drug_class: Optional[str] = None,
    dosage_form: Optional[str] = None,
    eda_id: Optional[str] = None,
    price_egp: Optional[float] = None,
) -> Dict[str, Any]:
    """
    Returns full clinical indication profile, diagnosis insights, and image URL
    for any Egyptian medicine or prescription entity.
    """
    # 1. Match against curated trade brands first (highest precision)
    trade_key = match_curated_key(drug_name or "")
    if trade_key:
        profile = dict(CURATED_CLINICAL_PROFILES[trade_key])
        profile["matched_by"] = f"curated_brand:{trade_key}"
    else:
        # 2. Match against active chemical substance
        gen_profile = match_generic_key(generic_name or "")
        if gen_profile:
            profile = dict(gen_profile)
            profile["matched_by"] = f"active_ingredient:{generic_name}"
        else:
            # 3. Dynamic category matching across 25,000 EDA classes & dosage forms
            search_corpus = f"{drug_class or ''} {generic_name or ''} {drug_name or ''} {dosage_form or ''}"
            matched = False
            for pattern, cat_profile in CATEGORY_FALLBACK_PATTERNS:
                if re.search(pattern, search_corpus, re.IGNORECASE):
                    profile = dict(cat_profile)
                    profile["matched_by"] = f"category_pattern:{pattern}"
                    matched = True
                    break

            if not matched:
                # 4. Universal clinical default
                form_clean = (dosage_form or "دواء").strip()
                profile = {
                    "category_ar": "مستحضر دوائي مسجل بهيئة الدواء المصرية",
                    "category_en": "EDA Registered Pharmaceutical",
                    "indication_short": f"مستحضر علاجي ({form_clean}) مسجل بالهيئة - مؤشر التشخيص: استشارة الطبيب المشرف على الحالة",
                    "what_it_does": "مستحضر صيدلاني علاجي يخضع لإشراف ومتابعة الطبيب المعالج والصيدلي.",
                    "what_it_treats": "الحالة المرضية المحددة في التشخيص الطبي للروشتة.",
                    "likely_diagnosis": "حالة مرضية محددة تستلزم العلاج وفقاً لتقييم الطبيب الفاحص.",
                    "mechanism": "يعمل وفقاً للخصائص العلاجية للمادة الفعالة المسجلة رسمياً بهيئة الدواء المصرية.",
                    "precautions": "يؤخذ بالجرعة المحددة في الروشتة وتحت إشراف الطبيب أو الصيدلي.",
                    "matched_by": "default_eda",
                }

    # Image URL generation for frontend:
    # If EDA ID exists, use `/api/drugs/{eda_id}/image`
    # Otherwise fallback to `/api/drugs/image-by-name?name=...`
    if eda_id:
        profile["image_url"] = f"/api/drugs/{eda_id}/image"
    elif drug_name:
        import urllib.parse
        encoded_name = urllib.parse.quote(drug_name.strip())
        encoded_form = urllib.parse.quote((dosage_form or "").strip())
        profile["image_url"] = f"/api/drugs/image-by-name?name={encoded_name}&form={encoded_form}"
    else:
        profile["image_url"] = "/api/drugs/EDA-00101/image"

    return profile


def infer_prescription_overall_diagnosis(medications: List[Dict[str, Any]]) -> Optional[str]:
    """
    Synthesizes the overall likely prescription diagnosis by analyzing
    all co-prescribed medicines on the paper.
    e.g. Flagyl + Antinal -> Gastroenteritis (نزلة معوية حادة)
    e.g. Augmentin + Congestal + Allvent -> Acute Respiratory Infection (نزلة برد ونزلة شعبية بكتيرية)
    """
    if not medications:
        return None

    names_and_classes = " ".join([
        f"{m.get('name', '')} {m.get('active_ingredient', '')} {m.get('raw_text', '')}"
        for m in medications
    ]).lower()

    # GI / Gastroenteritis pattern: Flagyl/Antinal/Smecta/Diax
    has_antinal = bool(re.search(r"\b(antinal|nifuroxazide|أنتينال|انتينال)\b", names_and_classes))
    has_flagyl = bool(re.search(r"\b(flagyl|metronidazole|فلاجيل|أميبا)\b", names_and_classes))
    has_antidiarrheal = has_antinal or has_flagyl

    # Diarrhea / Gut flora & Anemia pediatric co-prescription pattern
    has_probiotic = bool(re.search(r"\b(atlabacillus|lactobacillus|probiotic|أتلاباسيللوس|بروبيوتيك)\b", names_and_classes))
    has_iron = bool(re.search(r"\b(enrich|ferric|ferrous|iron|إنريتش|حديد)\b", names_and_classes))
    has_vit_c = bool(re.search(r"\b(cevilene|cevilin|cevitil|ascorbic|vitamin c|فيتامين سي|فيتامين ج)\b", names_and_classes))

    # Respiratory / Cold / Chest pattern:
    has_cold = bool(re.search(r"\b(congestal|1 2 3|one two three|flumox|comtrex|كونجستال)\b", names_and_classes))
    has_cough = bool(re.search(r"\b(allvent|ventolin|respipect|toplexil|farcolin|ألفنت|فنتولين)\b", names_and_classes))
    has_antibiotic = bool(re.search(r"\b(augmentin|curam|hibiotic|megamox|klacid|zithromax|ceftriaxone|cefaxone|septazole|أوجمنتين|كيورام|هاي بيوتك)\b", names_and_classes))
    has_nsaid = bool(re.search(r"\b(cataflam|voltaren|brufen|ketofan|كتافلام|بروفين|فولتارين)\b", names_and_classes))

    # Musculoskeletal / Neuro / Back pain pattern:
    has_muscle = bool(re.search(r"\b(dimra|myofen|relax|ديمرا|ميوفين)\b", names_and_classes))
    has_neuro = bool(re.search(r"\b(becozyme|betolvex|neurobion|milga|بيكوزيم|بيتولفكس|ميلجا)\b", names_and_classes))
    has_rub = bool(re.search(r"\b(rubalgine|moov|روبالجين|دهان|مرهم)\b", names_and_classes))

    # ENT / Ear, Nose & Throat pattern (Cipromega drops, Trimed Flu, Mucotec, Dongeel spray):
    has_ent = bool(re.search(r"\b(cipromega|trimed flu|mucotec|dongeel|ترايمد|سيبروميجا|ميوكوتك|دونجيل|أذن|حلق|لوزتين)\b", names_and_classes))

    # Summer vacation / Pediatric First-aid / Prickly heat & insect bites pattern:
    has_vacation_kit = bool(re.search(r"\b(solo|bringo|off|fenistil|cough\s*sed|سولو|برينجو|أوف|فينيستيل|كاف\s*سيد|حمو\s*النيل|مصيف|بحر|هرش|حكة)\b", names_and_classes))
    has_vacation_specific = bool(re.search(r"\b(solo|bringo|off|سولو|برينجو|أوف|حمو\s*النيل|مصيف|بحر)\b", names_and_classes))

    if has_vacation_kit and has_vacation_specific:
        return "حقيبة إسعافات طوارئ المصيف للأطفال (Summer Vacation / Beach First-Aid Kit): وقاية وعلاج حساسية ولدغات الحشرات، حمو النيل وحروق الشمس، ونوبات الكحة الطارئة."
    elif has_ent and (has_antibiotic or "cipromega" in names_and_classes):
        return "التهاب حاد باللوزتين مع التهاب الأذن الوسطى (Acute Tonsillitis & Otitis Media - AOM) واحتقان بالجهاز التنفسي."
    elif has_probiotic and has_iron:
        return "نزلة معوية أو إسهال حاد مع أنيميا نقص الحديد (Diarrhea & Iron Deficiency Anemia) لدى الأطفال."
    elif has_iron and (has_vit_c or "anemia" in names_and_classes):
        return "أنيميا نقص الحديد (Iron Deficiency Anemia) وفقر الدم."
    elif has_probiotic:
        return "إسهال حاد أو اضطراب في فلورا الأمعاء (Acute Diarrhea / Gut Flora Disruption)."
    elif has_antidiarrheal and (has_flagyl or has_antinal):
        return "نزلة معوية حادة (Gastroenteritis) مصحوبة بإسهال وميكروب معوي أو طفيليات (أميبا)."
    elif has_antibiotic and (has_cold or has_cough):
        return "عدوى بكتيرية حادة في الجهاز التنفسي العلوي أو السفلي (التهاب اللوزتين أو الحلق أو نزلة شعبية) مصحوبة بأعراض برد وكحة."
    elif has_cold and has_nsaid:
        return "نزلة برد حادة أو إنفلونزا موسمية مصحوبة بالتهاب واحتقان في الحلق وآلام بالجسم والحرارة."
    elif has_cough and not has_antibiotic:
        return "نزلة شعبية أو حساسية صدرية مصحوبة بكحة وبلغم أو ضيق في التنفس."
    elif (has_muscle or has_neuro or has_rub) and has_nsaid:
        return "التهاب وتقلص عضلي عصبي حاد، آلام أسفل الظهر أو الرقبة (Lumbago / Spasm)، أو عرق النسا."
    elif has_antibiotic and has_nsaid:
        return "التهاب بكتيري حاد مصحوب بألم وتورم (مثل خراج الأسنان، التهاب اللوزتين الحاد، أو صديد بالمسالك)."

    # Fallback to single primary medication diagnosis if only 1-2 meds
    for m in medications:
        diag = m.get("likely_diagnosis")
        if diag:
            return f"تشخيص يرجح: {diag}"

    return "حالة مرضية مشخصة من قبل الطبيب المعالج تستلزم متابعة الخطة العلاجية."
