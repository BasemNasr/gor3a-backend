    fun showingDrugs(current: Int, total: Int): String =
        if (isArabic) "عرض $current من أصل $total دواء" else "Showing $current of $total medicines"

    fun medCount(count: Int): String =
        if (isArabic) "$count دواء" else if (count == 1) "1 med" else "$count meds"

    fun doseNumber(number: Int): String =
        if (isArabic) "الجرعة رقم $number" else "Dose #$number"

    fun setTimeForDose(number: Int): String =
        if (isArabic) "تحديد وقت الجرعة ($number) ⏰" else "Set Time for Dose $number ⏰"

    fun prescribedMeds(count: Int): String =
        if (isArabic) "الأدوية المسجلة ($count):" else "Prescribed Medications ($count):"

    fun totalPrice(price: Double): String =
        if (isArabic) "الإجمالي: $price $currencyEgp" else "Total: $price $currencyEgp"

    fun formatTime(timeStr: String): String {
        val clean = timeStr.trim()
        return if (isArabic) {
            clean
                .replace("AM", "صباحاً", ignoreCase = true)
                .replace("PM", "مساءً", ignoreCase = true)
        } else {
            clean
                .replace("صباحاً", "AM")
                .replace("فجراً", "AM")
                .replace("مساءً", "PM")
                .replace("ظهراً", "PM")
                .replace("عصراً", "PM")
                .replace("ليلاً", "PM")
                .replace("منتصف الليل", "12:00 AM")
        }
    }
}

